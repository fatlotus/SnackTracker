const TRANSLATIONS: Record<Locale, Record<TranslationKey, string>> = {
  'en-US': enUS,
  'zh-CN': zhCN,
};

function interpolate(
  template: string,
  vars?: Record<string, string | number>,
): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    const val = vars[key];
    return val !== undefined ? String(val) : match;
  });
}

export interface I18nContextValue {
  locale: Locale;
  setLocale: (next: Locale) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
  formatDurationShort: (totalSeconds: number) => string;
  formatTimeAgo: (seconds: number) => string;
  formatLocalTime: (iso: string, timeZone?: string) => string;
  formatVolume: (volumeMl: number | null | undefined, unit: VolumeUnit) => string;
  computeBabyAgeLabel: (dob: string, refDateKey?: string) => string;
  buildTrendSeries: (
    dailyStats: readonly DailyStats[],
    unit?: VolumeUnit,
  ) => TrendDayPoint[];
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectInitialLocale);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
  }, []);

  useEffect(() => {
    if (typeof window !== 'undefined') {
      try {
        window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
      } catch {
        // Ignore storage errors
      }
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale;
      document.title = locale === 'zh-CN' ? '宝宝成长记录' : 'Baby Tracker';
    }
  }, [locale]);

  const t = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => {
      const dict = TRANSLATIONS[locale] ?? enUS;
      const template = dict[key] ?? enUS[key] ?? key;
      return interpolate(template, vars);
    },
    [locale],
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t,
      formatDurationShort: (totalSeconds) =>
        formatDurationShortRaw(totalSeconds, locale),
      formatTimeAgo: (seconds) => formatTimeAgoRaw(seconds, locale),
      formatLocalTime: (iso, timeZone = getLocalTimeZone()) =>
        formatLocalTimeRaw(iso, timeZone, locale),
      formatVolume: (volumeMl, unit) => formatVolumeRaw(volumeMl, unit, locale),
      computeBabyAgeLabel: (dob, refDateKey) =>
        computeBabyAgeLabelRaw(dob, refDateKey, locale),
      buildTrendSeries: (dailyStats, unit = 'ml') =>
        buildTrendSeriesRaw(dailyStats, unit, locale),
    }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return ctx;
}
